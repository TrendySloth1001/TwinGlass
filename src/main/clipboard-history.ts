// Searchable clipboard history (⇧⌘V / ⌘K), fed by the Mac clipboard and the phone's.
// Privacy: memory only (never written to disk), max 100 items, and anything a password manager
// marks as concealed (the nspasteboard.org convention) is skipped.
import { BrowserWindow, clipboard, ipcMain } from 'electron'

export interface ClipItem {
  id: number
  text: string
  at: number
  /** Where it was copied: on the Mac, or on the phone (synced over). */
  source: 'mac' | 'phone'
}

const MAX_ITEMS = 100
const MAX_TEXT = 100_000
let items: ClipItem[] = []
let nextId = 1
let enabled = true
let lastSeen = ''
/** Text the phone just sent: the next Mac clipboard change with it is "from the phone". */
let fromPhone: string | null = null

/**
 * Password managers mark secrets with these pasteboard types (nspasteboard.org). Electron 45 checks
 * raw pasteboard types via its `electron application/osclipboard;format="…"` mime syntax.
 */
const CONCEALED = ['org.nspasteboard.ConcealedType', 'org.nspasteboard.TransientType', 'org.nspasteboard.AutoGeneratedType']
async function concealed(): Promise<boolean> {
  for (const t of CONCEALED) {
    if (await clipboard.has(`electron application/osclipboard;format="${t}"`).catch(() => false)) return true
  }
  return false
}

function add(text: string, source: ClipItem['source']): void {
  if (!enabled || !text.trim() || text.length > MAX_TEXT) return
  items = [{ id: nextId++, text, at: Date.now(), source }, ...items.filter((i) => i.text !== text)].slice(0, MAX_ITEMS)
  for (const w of BrowserWindow.getAllWindows()) w.webContents.send('clipboard:history-changed')
}

/** Called when the phone's clipboard arrives (session-ipc writes it to the Mac clipboard). */
export function notePhoneClipboard(text: string): void {
  fromPhone = text
}

/** Electron has no clipboard-change event: poll (a string compare every 750 ms is negligible). */
export function startClipboardHistory(): void {
  let busy = false
  void clipboard.readText().then((t) => (lastSeen = t), () => {})
  setInterval(() => {
    if (busy) return
    busy = true
    void (async () => {
      const text = await clipboard.readText()
      if (text === lastSeen) return
      lastSeen = text
      if (await concealed()) return
      add(text, fromPhone === text ? 'phone' : 'mac')
      if (fromPhone === text) fromPhone = null
    })()
      .catch(() => {})
      .finally(() => (busy = false))
  }, 750)
}

export function registerClipboardHistoryIpc(): void {
  ipcMain.handle('clipboard:history', () => ({ enabled, items }))
  ipcMain.handle('clipboard:history-set-enabled', (_e, on: unknown) => {
    enabled = on === true
    if (!enabled) items = []
  })
  ipcMain.handle('clipboard:history-clear', () => {
    items = []
  })
  ipcMain.handle('clipboard:history-remove', (_e, id: unknown) => {
    items = items.filter((i) => i.id !== id)
  })
  /** Put an item back on the Mac clipboard (the renderer sends it to the phone separately). */
  ipcMain.handle('clipboard:history-use', async (_e, id: unknown) => {
    const it = items.find((i) => i.id === id)
    if (!it) return false
    lastSeen = it.text // not a new copy: don't reorder the history
    await clipboard.writeText(it.text)
    return true
  })
}
